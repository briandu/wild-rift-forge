export function bannerFocusFor(slug: string): BannerFocus {
  return BANNER_FOCUS_BY_SLUG[slug.toLowerCase()] ?? DEFAULT_BANNER_FOCUS;
}

/** Tall poster tiles crop splash as a portrait. Keep special Y for non-humanoid heads. */
export function cardFocusFor(slug: string): BannerFocus {
  const focus = bannerFocusFor(slug);
  return { x: focus.x, y: focus.y > 24 ? focus.y : 22 };
}
